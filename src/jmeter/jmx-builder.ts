function cookieManager(): string {
  return `<CookieManager guiclass="CookiePanel" testclass="CookieManager" testname="HTTP Cookie Manager" enabled="true">
          <collectionProp name="CookieManager.cookies"/>
          <boolProp name="CookieManager.clearEachIteration">false</boolProp>
          <boolProp name="CookieManager.controlledByThreadGroup">false</boolProp>
        </CookieManager>
        <hashTree/>`
}

function headerManager(model: TestPlanModel): string {
  const headers: { name: string; value: string }[] = [{ name: 'Accept', value: 'application/json' }]
  if (model.auth?.type === 'bearer') {
    const variable = model.auth.tokenVar || 'token'
    const headerName = model.auth.headerName || 'Authorization'
    const prefix = model.auth.headerPrefix ?? 'Bearer '
    headers.push({ name: headerName, value: `${prefix}\${${variable}}` })
  }
  const elements = headers.map((header) => `<elementProp name="" elementType="Header">
              <stringProp name="Header.name">${esc(header.name)}</stringProp>
              <stringProp name="Header.value">${esc(header.value)}</stringProp>
            </elementProp>`).join('\n')
  return `<HeaderManager guiclass="HeaderPanel" testclass="HeaderManager" testname="HTTP Header Manager" enabled="true">
          <collectionProp name="HeaderManager.headers">
            ${elements}
          </collectionProp>
        </HeaderManager>
        <hashTree/>`
}

function authManager(model: TestPlanModel): string {
  if (model.auth?.type !== 'basic') return ''
  return `<AuthManager guiclass="AuthPanel" testclass="AuthManager" testname="HTTP Authorization Manager" enabled="true">
          <collectionProp name="AuthManager.auth_list">
            <elementProp name="" elementType="Authorization">
              <stringProp name="Authorization.url">${esc(model.baseUrl)}</stringProp>
              <stringProp name="Authorization.username">${esc(model.auth.username ?? '')}</stringProp>
              <stringProp name="Authorization.password">${esc(model.auth.password ?? '')}</stringProp>
              <stringProp name="Authorization.domain"></stringProp>
              <stringProp name="Authorization.realm"></stringProp>
              <stringProp name="Authorization.mechanism">BASIC</stringProp>
            </elementProp>
          </collectionProp>
          <boolProp name="AuthManager.controlledByThreadGroup">false</boolProp>
        </AuthManager>
        <hashTree/>`
}

function transaction(name: string, calls: HttpCall[]): string {
  const samplers = calls.map((call) => sampler(call)).join('\n')
  return `<TransactionController guiclass="TransactionControllerGui" testclass="TransactionController" testname="${esc(name)}" enabled="true">
          <boolProp name="TransactionController.includeTimers">false</boolProp>
          <boolProp name="TransactionController.parent">true</boolProp>
        </TransactionController>
        <hashTree>
          ${samplers}
        </hashTree>`
}

function sampler(call: HttpCall): string {
  const method = call.method.toUpperCase()
  const path = call.path.startsWith('/') ? call.path : `/${call.path}`
  const children = [
    thinkTimer(call.thinkTimeMs),
    callHeaderManager(call),
    ... (call.extractors ?? []).map(extractor),
    ... (call.assertions ?? []).map(assertion)
  ].filter((part) => part.length > 0)

  return `<HTTPSamplerProxy guiclass="HttpTestSampleGui" testclass="HTTPSamplerProxy" testname="${esc(call.name)}" enabled="true">
            ${argumentsXml(call.body)}
            <stringProp name="HTTPSampler.domain"></stringProp>
            <stringProp name="HTTPSampler.port"></stringProp>
            <stringProp name="HTTPSampler.protocol"></stringProp>
            <stringProp name="HTTPSampler.contentEncoding">UTF-8</stringProp>
            <stringProp name="HTTPSampler.path">${esc(path)}</stringProp>
            <stringProp name="HTTPSampler.method">${esc(method)}</stringProp>
            <boolProp name="HTTPSampler.follow_redirects">true</boolProp>
            <boolProp name="HTTPSampler.auto_redirects">false</boolProp>
            <boolProp name="HTTPSampler.use_keepalive">true</boolProp>
            <boolProp name="HTTPSampler.DO_MULTIPART_POST">false</boolProp>
            <stringProp name="HTTPSampler.embedded_url_re"></stringProp>
            <stringProp name="HTTPSampler.connect_timeout"></stringProp>
            <stringProp name="HTTPSampler.response_timeout"></stringProp>
          </HTTPSamplerProxy>
          <hashTree>
            ${children.join('\n')}
          </hashTree>`
}

function argumentsXml(body: string | undefined): string {
  if (body == null) {
    return `<boolProp name="HTTPSampler.postBodyRaw">false</boolProp>
            <elementProp name="HTTPsampler.Arguments" elementType="Arguments" guiclass="HTTPArgumentsPanel" testclass="Arguments" enabled="true">
              <collectionProp name="Arguments.arguments"/>
            </elementProp>`
  }
  return `<boolProp name="HTTPSampler.postBodyRaw">true</boolProp>
            <elementProp name="HTTPsampler.Arguments" elementType="Arguments">
              <collectionProp name="Arguments.arguments">
                <elementProp name="" elementType="HTTPArgument">
                  <boolProp name="HTTPArgument.always_encode">false</boolProp>
                  <stringProp name="Argument.value">${esc(body)}</stringProp>
                  <stringProp name="Argument.metadata">=</stringProp>
                </elementProp>
              </collectionProp>
            </elementProp>`
}

function thinkTimer(delay: number | undefined): string {
  if (delay == null || delay <= 0) return ''
  return `<ConstantTimer guiclass="ConstantTimerGui" testclass="ConstantTimer" testname="Think Time" enabled="true">
              <stringProp name="ConstantTimer.delay">${Math.floor(delay)}</stringProp>
            </ConstantTimer>
            <hashTree/>`
}

function callHeaderManager(call: HttpCall): string {
  const headers = { ...(call.headers ?? {}) }
  const hasContentType = Object.keys(headers).some((name) => name.toLowerCase() === 'content-type')
  if (call.body != null && !hasContentType) {
    headers['Content-Type'] = call.contentType || 'application/json'
  }
  const entries = Object.entries(headers)
  if (entries.length === 0) return ''
  const elements = entries.map(([name, value]) => `<elementProp name="" elementType="Header">
                <stringProp name="Header.name">${esc(name)}</stringProp>
                <stringProp name="Header.value">${esc(value)}</stringProp>
              </elementProp>`).join('\n')
  return `<HeaderManager guiclass="HeaderPanel" testclass="HeaderManager" testname="${esc(call.name)} Headers" enabled="true">
              <collectionProp name="HeaderManager.headers">
                ${elements}
              </collectionProp>
            </HeaderManager>
            <hashTree/>`
}

function extractor(item: NonNullable<HttpCall['extractors']>[number]): string {
  const match = item.matchNumber ?? 1
  const fallback = item.defaultValue ?? 'NOT_FOUND'
  if (item.source === 'regex') {
    return `<RegexExtractor guiclass="RegexExtractorGui" testclass="RegexExtractor" testname="${esc(`Extract ${item.name}`)}" enabled="true">
              <stringProp name="RegexExtractor.useHeaders">false</stringProp>
              <stringProp name="RegexExtractor.refname">${esc(item.name)}</stringProp>
              <stringProp name="RegexExtractor.regex">${esc(item.expression)}</stringProp>
              <stringProp name="RegexExtractor.template">$1$</stringProp>
              <stringProp name="RegexExtractor.default">${esc(fallback)}</stringProp>
              <stringProp name="RegexExtractor.match_number">${match}</stringProp>
            </RegexExtractor>
            <hashTree/>`
  }
  return `<JSONPostProcessor guiclass="JSONPostProcessorGui" testclass="JSONPostProcessor" testname="${esc(`Extract ${item.name}`)}" enabled="true">
              <stringProp name="JSONPostProcessor.referenceNames">${esc(item.name)}</stringProp>
              <stringProp name="JSONPostProcessor.jsonPathExprs">${esc(item.expression)}</stringProp>
              <stringProp name="JSONPostProcessor.match_numbers">${match}</stringProp>
              <stringProp name="JSONPostProcessor.defaultValues">${esc(fallback)}</stringProp>
            </JSONPostProcessor>
            <hashTree/>`
}

function assertion(item: NonNullable<HttpCall['assertions']>[number]): string {
  if (item.type === 'status') {
    return responseAssertion(`Status ${item.expected}`, 'Assertion.response_code', 8, item.expected)
  }
  if (item.type === 'text') {
    return responseAssertion(`Body contains ${item.expected}`, 'Assertion.response_data', 2, item.expected)
  }
  const expression = jsonPathToJmes(item.jsonPath || item.expected)
  return `<JMESPathAssertion guiclass="JMESPathAssertionGui" testclass="JMESPathAssertion" testname="${esc(`JSON ${expression}`)}" enabled="true">
              <stringProp name="JMES_PATH">${esc(expression)}</stringProp>
              <stringProp name="EXPECTED_VALUE">${esc(item.expected)}</stringProp>
              <boolProp name="JSONVALIDATION">true</boolProp>
              <boolProp name="EXPECT_NULL">false</boolProp>
              <boolProp name="INVERT">false</boolProp>
              <boolProp name="ISREGEX">false</boolProp>
            </JMESPathAssertion>
            <hashTree/>`
}

function responseAssertion(name: string, field: string, testType: number, expected: string): string {
  return `<ResponseAssertion guiclass="AssertionGui" testclass="ResponseAssertion" testname="${esc(name)}" enabled="true">
              <collectionProp name="Asserion.test_strings">
                <stringProp name="0">${esc(expected)}</stringProp>
              </collectionProp>
              <stringProp name="Assertion.custom_message"></stringProp>
              <stringProp name="Assertion.test_field">${field}</stringProp>
              <boolProp name="Assertion.assume_success">false</boolProp>
              <intProp name="Assertion.test_type">${testType}</intProp>
            </ResponseAssertion>
            <hashTree/>`
}

export function jsonPathToJmes(expression: string): string {
  let path = expression.trim()
  if (path.startsWith('$.')) path = path.slice(2)
  else if (path === '$') path = '@'
  path = path.replace(/\['([^']+)'\]/g, '.$1').replace(/\[\"([^\"]+)\"\]/g, '.$1')
  return path.replace(/^\./, '')
}

