import { parseTestPlan, type HttpCall, type TestPlanModel } from '../model/test-plan'

export interface BuildOptions {
  mode?: 'run' | 'validate'
}

export function assertJmxWellFormed(xml: string): void {
  const required = [
    '<jmeterTestPlan',
    '<ThreadGroup',
    '<HTTPSamplerProxy',
    'HTTP Cookie Manager',
    'HTTP Request Defaults',
    '<TransactionController',
    '</jmeterTestPlan>'
  ]
  for (const token of required) {
    if (!xml.includes(token)) throw new Error(`JMX is missing ${token}`)
  }
  const open = xml.match(/<hashTree>/g)?.length ?? 0
  const close = xml.match(/<\/hashTree>/g)?.length ?? 0
  if (open !== close) throw new Error(`JMX hashTree elements are unbalanced (${open} open, ${close} close)`)
}

export function buildJmx(input: TestPlanModel, options: BuildOptions = {}): string {
  const model = parseTestPlan(input)
  const mode = options.mode ?? 'run'
  const base = new URL(model.baseUrl)
  const protocol = base.protocol.replace(':', '')
  const domain = base.hostname
  const port = base.port || (protocol === 'https' ? '443' : '80')
  const threads = model.load.threads
  const duration = mode === 'validate' ? 1 : model.load.durationSec
  const ramp = mode === 'validate' ? 0 : model.load.rampUpSec
  const scheduler = mode === 'validate' ? 'false' : 'true'
  const loops = mode === 'validate' ? '1' : '-1'
  const threadGroupEnabled = mode === 'validate' ? 'false' : 'true'

  const children = [
    httpDefaults(protocol, domain, port),
    cookieManager(),
    headerManager(model),
    authManager(model),
    ...model.scenarios.map((scenario) => transaction(scenario.name, scenario.calls))
  ].filter((part) => part.length > 0)

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<jmeterTestPlan version="1.2" properties="5.0" jmeter="5.6.3">
  <hashTree>
    <TestPlan guiclass="TestPlanGui" testclass="TestPlan" testname="${esc(model.name)}" enabled="true">
      <stringProp name="TestPlan.comments">Generated by Vireo. Edit the test-plan model, not this file.</stringProp>
      <boolProp name="TestPlan.functional_mode">false</boolProp>
      <boolProp name="TestPlan.tearDown_on_shutdown">true</boolProp>
      <boolProp name="TestPlan.serialize_threadgroups">false</boolProp>
      ${userDefinedVariables(model)}
      <stringProp name="TestPlan.user_define_classpath"></stringProp>
    </TestPlan>
    <hashTree>
      <ThreadGroup guiclass="ThreadGroupGui" testclass="ThreadGroup" testname="Users" enabled="${threadGroupEnabled}">
        <stringProp name="ThreadGroup.on_sample_error">continue</stringProp>
        <elementProp name="ThreadGroup.main_controller" elementType="LoopController" guiclass="LoopControlPanel" testclass="LoopController" testname="Loop Controller" enabled="true">
          <boolProp name="LoopController.continue_forever">false</boolProp>
          <stringProp name="LoopController.loops">${loops}</stringProp>
        </elementProp>
        <stringProp name="ThreadGroup.num_threads">${threads}</stringProp>
        <stringProp name="ThreadGroup.ramp_time">${ramp}</stringProp>
        <boolProp name="ThreadGroup.scheduler">${scheduler}</boolProp>
        <stringProp name="ThreadGroup.duration">${duration}</stringProp>
        <stringProp name="ThreadGroup.delay">0</stringProp>
        <boolProp name="ThreadGroup.same_user_on_next_iteration">true</boolProp>
      </ThreadGroup>
      <hashTree>
        ${children.join('\n')}
        ${simpleDataWriter()}
      </hashTree>
    </hashTree>
  </hashTree>
</jmeterTestPlan>
`
  assertJmxWellFormed(xml)
  return xml
}

function esc(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function userDefinedVariables(model: TestPlanModel): string {
  const tokenVar = model.auth?.tokenVar || 'token'
  const token = model.auth?.type === 'bearer' ? model.auth.token ?? '' : ''
  if (model.auth?.type !== 'bearer') {
    return `<elementProp name="TestPlan.user_defined_variables" elementType="Arguments" guiclass="ArgumentsPanel" testclass="Arguments" testname="User Defined Variables" enabled="true">
        <collectionProp name="Arguments.arguments"/>
      </elementProp>`
  }
  return `<elementProp name="TestPlan.user_defined_variables" elementType="Arguments" guiclass="ArgumentsPanel" testclass="Arguments" testname="User Defined Variables" enabled="true">
        <collectionProp name="Arguments.arguments">
          <elementProp name="${esc(tokenVar)}" elementType="Argument">
            <stringProp name="Argument.name">${esc(tokenVar)}</stringProp>
            <stringProp name="Argument.value">${esc(token)}</stringProp>
            <stringProp name="Argument.metadata">=</stringProp>
          </elementProp>
        </collectionProp>
      </elementProp>`
}

